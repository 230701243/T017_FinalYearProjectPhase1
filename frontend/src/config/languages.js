export const LANGUAGE_MAP = Object.fromEntries(LANGUAGES.map(l => [l.code, l]))

export const DEFAULT_LANGUAGE = 'en'

/**
 * Returns a supported browser Intl locale for number/date formatting,
 * falling back to hi-IN or en-IN if the locale is unsupported by browser Intl.
 */
export function getFormattingLocale(langCode) {
  const conf = LANGUAGE_MAP[langCode] || LANGUAGE_MAP[DEFAULT_LANGUAGE]
  const candidate = conf.locale
  try {
    if (typeof Intl !== 'undefined' && Intl.NumberFormat && Intl.NumberFormat.supportedLocalesOf([candidate]).length > 0) {
      return candidate
    }
  } catch (e) {}
  return conf.fallbackLocale || (conf.group === 'indian' ? 'en-IN' : 'en-US')
}

/**
 * Returns true if the language is RTL (Arabic, Urdu, Sindhi, Kashmiri)
 */
export function isRtlLanguage(langCode) {
  return LANGUAGE_MAP[langCode]?.direction === 'rtl'
}

